/** Western digits for whatever digits were typed (an Arabic keyboard types ٠–٩ and the Arabic decimal mark). */
export function toAsciiDigits(raw: string): string {
  return raw
    .replace(/[٠-٩]/g, (d) => String("٠١٢٣٤٥٦٧٨٩".indexOf(d)))
    .replace(/[۰-۹]/g, (d) => String("۰۱۲۳۴۵۶۷۸۹".indexOf(d)))
    .replace(/٫/g, ".")
    .trim();
}

/** A whole number within [min, max], or null. */
export function parseWhole(raw: string, min: number, max: number): number | null {
  const ascii = toAsciiDigits(raw);
  if (!/^\d{1,9}$/.test(ascii)) return null;
  const n = Number(ascii);
  return n >= min && n <= max ? n : null;
}
